// Heading text -> URL fragment. Keep in sync with slugify() in
// scripts/build-docs-index.mjs (the search index links to these ids).
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
